/**
 * bcrypt 配置 — 密码哈希参数
 *
 * 配置来源：
 * - 使用固定值（也可扩展为从环境变量读取）
 * - 使用 registerAs 将配置注册为命名空间配置
 *
 * 配置项说明：
 * | 环境变量    | 默认值 | 说明                |
 * |-----------|-------|-------------------|
 * | BCRYPT_SALT_ROUNDS | 10 | 盐轮数（密码哈希强度）|
 *
 * saltRounds 说明：
 * - 轮数越多，哈希越慢，但安全性越高
 * - 10 轮：约 100ms 哈希时间，平衡安全与性能
 * - 生产环境建议 12-14 轮
 * - 每增加 1 轮，时间翻倍
 *
 * 安全建议：
 * - 不要降低轮数，这会降低密码哈希的安全性
 * - 轮数选择需权衡：服务器性能 vs 安全性
 */

import { registerAs } from '@nestjs/config';

export const bcryptConfig = registerAs('bcrypt', () => ({
  /**
   * bcrypt 盐轮数
   * - 控制密码哈希的计算复杂度
   * - 10 轮：约 100ms，平衡安全与性能
   * - ⚠️ 生产环境建议 12-14 轮
   * - 轮数越高安全性越好，但服务器负载越大
   */
  saltRounds: 10,
}));
